STYLE_LIMIT = 1000  # Suno Style 칸 한도


def fit_style(text: str, limit: int = STYLE_LIMIT) -> str:
    """Suno Style 한도(1000자)를 넘으면 뒤에서부터 쉼표 구절 단위로 잘라 맞춘다. 앞쪽(장르·보컬·악기)이 더 중요하다."""
    text = " ".join((text or "").split())
    if len(text) <= limit:
        return text
    cut = text[: limit - 1]
    for sep in (". ", ", ", "; ", " "):
        i = cut.rfind(sep)
        if i > limit * 0.6:
            cut = cut[:i]
            break
    return cut.rstrip(" ,;") + "."


